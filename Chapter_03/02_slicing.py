str="Abhishek"

print("Positive Index Slicing:")
print(str[0:8])
print(str[0:])
print(str[:8])
print(str[:])

print("Slicing With Skip Value:")
print(str[0:8:2])

print("Negative Index Slicing:")
print(str[-8:-1])
print(str[-8:])
print(str[:-7])

